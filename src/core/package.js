async function contentIdentity(files) {
  const hashes = {};
  for (const name of Object.keys(files).sort()) hashes[name] = await sha256hex(files[name]);
  return { algorithm: "SHA-256", scope: "all package files except verification.json", files: hashes, content_digest: await sha256hex(canonical(hashes)) };
}

export async function buildPackage(input) {
  const manifest = structuredClone(input.manifest);
  manifest.verification = { status: "CONFORMANCE_PASS", evidence: "verification.json", digest_scope: "all package files except verification.json" };
  const generated = generateFiles({ ...input, manifest });
  const report = verifyConnector({ manifest, files: generated.files, preview: input.preview });
  if (report.status !== "CONFORMANCE_PASS") {
    manifest.verification = { status: "HOLD", evidence: null, digest_scope: null };
    return { name: generated.name, manifest, files: {}, zip: null, package_hash: null, content_digest: null, report, check_text: formatCheckLines(report) };
  }
  const identity = await contentIdentity(generated.files);
  generated.files["verification.json"] = JSON.stringify({ verification_version: "connectordome.verification/v0.1.2", status: report.status, ...identity, checks: report.checks }, null, 2) + "\n";
  const zip = zipStore(generated.files);
  return { name: generated.name, manifest, files: generated.files, zip, package_hash: await sha256hex(zip), content_digest: identity.content_digest, report, check_text: formatCheckLines(report) };
}

export function manifestFromBuild({ kind, name, inspection, mapping, description }) {
  const observedKind = inspection?.provenance_class === "TEST_FIXTURE" ? "fixture" : kind;
  const provenance_mode = provenanceForSourceKind(observedKind);
  const suggestion = suggestForField(mapping.field || "");
  return {
    name: name || `dome-${observedKind}`, version: "0.1.2", publisher: mapping.publisher || "guest", category: mapping.category || "Other",
    source_kind: observedKind, source_url: observedKind === "fixture" ? null : inspection?.url || null, source_host: inspection?.source || null,
    source_reference: observedKind === "fixture" ? "embedded:fixture.json" : inspection?.url || null, source_declared: kind, source_observed: observedKind,
    provenance_mode, provenance_declared: mapping.provenance_mode || null, provenance_observed: inspection?.provenance_class || null, provenance_verified: "ACQUISITION_PATH_ONLY",
    http_methods: ["GET"], actuation: "NONE", read_only: true, asf_compatibility: "ASF ReceptorEvent v0.1 + freshness extension v0.1.2",
    capabilities: [{ capability_id: mapping.capability, field: mapping.field, units: mapping.units ?? null, data_type: mapping.data_type || "number", time_field: mapping.time_field || null, modality: mapping.modality || suggestion.modality }],
    transport: observedKind === "fixture" ? "embedded" : observedKind === "simulator" ? "none" : "https-get",
    acquisition: observedKind === "fixture" ? "embedded_fixture" : observedKind === "text_claim" ? "operator_text" : "GET",
    sampling_semantics: "polled_snapshot", poll_interval_s: mapping.poll_interval_s ?? (kind === "stream" ? 1 : null), freshness_threshold_s: mapping.freshness_threshold_s ?? 300,
    observation_mode: observedKind === "fixture" ? "historical" : mapping.observation_mode || "current", unavailable_behavior: "UNAVAILABLE", no_fabrication: true,
    ...(observedKind === "simulator" ? { sim_seed: mapping.sim_seed ?? 1 } : {}),
    ...(observedKind === "text_claim" ? { statement: inspection?.body?.statement ?? null, claimed_value: inspection?.body?.claimed ?? null } : {}),
    secret_ref: mapping.secret_ref || null, description: description || "", demo: (mapping.publisher || "guest") === "ConnectorDome", generated_by: "ConnectorDome",
    generator_license: "Apache-2.0", license: mapping.license || "UNSPECIFIED", phone_home: false, source_endorsement: false, multiple_capabilities_supported: false,
  };
}
