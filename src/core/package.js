export async function buildPackage(input) {
  const { name, files } = generateFiles(input);
  const report = verifyConnector({
    manifest: input.manifest,
    files,
    preview: input.preview,
  });
  const zip = zipStore(files);
  const package_hash = await sha256hex(zip);
  return {
    name,
    files,
    zip,
    package_hash,
    report,
    check_text: formatCheckLines(report),
  };
}

export function manifestFromBuild({ kind, name, inspection, mapping, description }) {
  const cap = {
    capability_id: mapping.capability,
    field: mapping.field,
    units: mapping.units ?? null,
    data_type: mapping.data_type || "number",
    time_field: mapping.time_field || null,
  };
  const provenance_mode =
    kind === "simulator" ? "SIMULATION" : kind === "text_claim" ? "TEXT_CLAIM" : kind === "fixture" ? "TEST_FIXTURE" : "REMOTE_FEED";
  const publisher = mapping.publisher || "guest";
  const license = mapping.license || "UNSPECIFIED";
  return {
    name: name || `dome-${kind}`,
    version: "0.1.0",
    publisher,
    category: mapping.category || "Other",
    source_kind: kind,
    source_url: inspection?.url || null,
    source_host: inspection?.source || null,
    http_methods: ["GET"],
    actuation: "NONE",
    read_only: true,
    provenance_mode,
    asf_compatibility: "ASF ReceptorEvent v0.1 / post-v0.1 TEST_FIXTURE",
    capabilities: [cap],
    sampling_semantics: "polled_snapshot",
    poll_interval_s: mapping.poll_interval_s ?? (kind === "stream" ? 1 : null),
    unavailable_behavior: "UNAVAILABLE",
    no_fabrication: true,
    secret_ref: mapping.secret_ref || null,
    description: description || "",
    demo: publisher === "ConnectorDome",
    verification: "pending",
    generated_by: "ConnectorDome",
    generator_license: "Apache-2.0",
    license,
    phone_home: false,
    source_endorsement: false,
  };
}
